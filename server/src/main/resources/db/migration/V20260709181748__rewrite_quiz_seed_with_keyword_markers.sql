-- 시드 해설을 "핵심 N줄 정리"(#8) 형태로 다시 쓰고, 키워드 위치를 [[마커]]로 저작한다 (#43).
--
-- 왜 바꾸는가
--   1) explanation_summary는 생성 파이프라인(#26)이 개행으로 나뉜 N줄(현재 3줄)로 뽑는다.
--      초기 시드(V20260708171651)는 스키마 검증용 임시 데이터라 한 문장이었다 — 실제 계약과 어긋난다.
--   2) 해설 화면(S4)은 본문 속 키워드를 하이라이트하고 탭하면 툴팁을 띄운다(#12). 그러려면
--      "키워드가 본문 어디에 있는가"를 알아야 하는데, 한국어는 단어 경계가 없어 서버가 문자열
--      매칭으로 찾으면 오탐이 난다(키워드 '정렬'이 '정렬되지 않은'의 '정렬'에도 걸린다).
--      그래서 위치를 저작 시점에 [[키워드]] 마커로 확정한다. 서버가 파싱해 평문 + 구간으로 내려준다.
--
-- 마커 규칙 (ExplanationTextParser)
--   - 마커 안 문자열은 quiz_keyword.keyword와 정확히 일치해야 한다. 조사는 마커 밖에 둔다.
--   - 사전에 없는 [[...]]는 마커로 보지 않고 리터럴 텍스트로 통과시킨다.
--   - 한 컬럼 안에서 같은 키워드는 첫 등장 1회만 마킹한다(과다 강조 방지).
--   - 마커는 DB 저장 형식일 뿐 API 응답에는 노출되지 않는다.
--
-- 적용된 마이그레이션은 수정하지 않는 규칙에 따라 UPDATE/INSERT로 보정한다.
-- 실제 콘텐츠는 #26이 완성되면 대체된다. 그 전까지 FE(#12)는 이 시드로 개발한다.

-- 1) OX (TCP) — 키워드 '비연결형'은 해설 본문이 아니라 오답 해설에만 등장한다.
--    실제 생성물에서도 키워드의 절반가량이 summary 밖에 있어, 그 상황을 시드로 재현한다.
UPDATE quiz
SET explanation_summary          = 'TCP는 데이터를 주고받기 전에 연결을 먼저 수립하는 [[연결 지향]] 프로토콜이다.
연결은 [[3-way handshake]]로 양쪽의 송수신 준비 상태를 확인한 뒤 맺어진다.
그래서 데이터가 보낸 순서대로 빠짐없이 도착하도록 보장할 수 있다.',
    wrong_answer_explanation = 'UDP와 헷갈리기 쉽다 — UDP는 [[비연결형]]이라 [[3-way handshake]] 없이 곧바로 데이터를 보낸다.'
WHERE id = 1;

INSERT INTO quiz_keyword (quiz_id, keyword, description)
VALUES (1, '3-way handshake', '연결을 맺기 위해 SYN, SYN-ACK, ACK 세 단계로 패킷을 주고받는 절차'),
       (1, '비연결형', '연결을 수립하지 않고 곧바로 데이터를 전송하는 방식');

-- 2) 사지선다 (시간복잡도)
UPDATE quiz
SET explanation_summary      = '바깥 반복문과 안쪽 반복문이 각각 n번씩 실행된다.
전체 연산 횟수가 n의 제곱에 비례하므로 [[시간복잡도]]는 O(n^2)이다.
입력이 10배 늘면 실행 시간은 약 100배로 늘어난다.',
    explanation_example      = '정렬되지 않은 배열을 버블 정렬로 정리할 때도 같은 패턴이 나오며, [[빅오 표기법]]으로 O(n^2)이라고 쓴다.',
    wrong_answer_explanation = 'O(n)으로 착각하기 쉽다 — 바깥 반복문만 보고 안쪽 반복문을 놓치면 [[시간복잡도]]를 한 단계 낮게 센다.'
WHERE id = 2;

INSERT INTO quiz_keyword (quiz_id, keyword, description)
VALUES (2, '빅오 표기법', '입력 크기가 커질 때 연산 횟수가 늘어나는 추세를 나타내는 표기법');

